#[cfg(unix)]
#[path = "blueice-downloads/unix.rs"]
mod unix;

#[cfg(unix)]
fn main() -> std::process::ExitCode {
    unix::main()
}

#[cfg(not(unix))]
fn main() -> std::process::ExitCode {
    eprintln!("blueice-downloads requires Unix-domain socket support on this platform");
    std::process::ExitCode::FAILURE
}
