use blueice_downloads::cli::{parse_args, run};
use std::process::ExitCode;

fn main() -> ExitCode {
    let args = match parse_args(std::env::args().skip(1)) {
        Ok(args) => args,
        Err(message) => {
            eprintln!("blueice-downloads: {message}");
            return ExitCode::from(2);
        }
    };
    match run(args) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("blueice-downloads: {e}");
            ExitCode::FAILURE
        }
    }
}
