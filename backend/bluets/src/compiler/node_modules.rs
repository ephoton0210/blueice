//! Node file formats and verbatim declarations on an already owned graph.

use super::*;
use crate::parser::Declaration;

pub(super) fn validate(project: &Project, options: &CompilerOptions) -> Vec<Diagnostic> {
    let mut diagnostics = Vec::new();
    for (id, module) in &project.modules {
        if is_declaration_module(id) || is_external_library_module(id) {
            continue;
        }
        if project.module_kind(id, options.module_kind) != ModuleKind::CommonJs {
            continue;
        }
        let tokens = crate::lex(id, &module.source).unwrap_or_default();
        let syntax_code = if id.ends_with(".cts")
            || !matches!(
                options.module_kind,
                ModuleKind::Node16 | ModuleKind::NodeNext
            ) {
            1286
        } else {
            1295
        };
        let mut syntax_error = |span: &SourceSpan, code, arguments| {
            diagnostics.push(
                Diagnostic::error(
                    DiagnosticCode::UnsupportedSyntax,
                    span.clone(),
                    "module declaration is incompatible with the selected Node file format",
                )
                .with_typescript(code, arguments),
            );
        };
        for declaration in &module.declarations {
            if let Declaration::Import(import) = declaration {
                if options.verbatim_module_syntax
                    && !import.equals_require
                    && !import.is_type_only()
                    && !import.bindings.is_empty()
                {
                    for binding in import.bindings.iter().filter(|binding| !binding.type_only) {
                        syntax_error(&binding.span, syntax_code, Vec::new());
                    }
                }
                if options.module_kind == ModuleKind::Node16 && !import.is_type_only() {
                    if let Some(target) = project.resolved_import(id, import) {
                        if project.module_kind(target, ModuleKind::CommonJs) == ModuleKind::Esm {
                            syntax_error(
                                &import.specifier_span,
                                1479,
                                vec![import.specifier.clone()],
                            );
                        }
                    }
                }
                continue;
            }
            if !options.verbatim_module_syntax {
                continue;
            }
            let exported = match declaration {
                Declaration::Variable(value) => value.exported && !value.declared,
                Declaration::Function(value) => {
                    value.exported && !value.declared && !value.overload
                }
                Declaration::Class(value) => value.exported,
                Declaration::Enum(value) => value.exported && !value.declared,
                Declaration::Namespace(value) => value.exported && !value.declared,
                _ => false,
            };
            if exported {
                if let Some(token) = tokens.iter().find(|token| {
                    token.is("export")
                        && token.start >= declaration.span().start
                        && token.end <= declaration.span().end
                }) {
                    syntax_error(
                        &SourceSpan::new(id, token.start, token.end),
                        1287,
                        Vec::new(),
                    );
                }
            } else if matches!(declaration, Declaration::DefaultExport(_))
                || matches!(declaration,
                Declaration::ValueExport(value) if !value.export_assignment && !value.is_type_only())
            {
                if let Some(token) = tokens
                    .iter()
                    .find(|token| token.is("export") && token.start == declaration.span().start)
                {
                    syntax_error(
                        &SourceSpan::new(id, token.start, token.end),
                        syntax_code,
                        Vec::new(),
                    );
                }
            }
        }
    }
    diagnostics
}
