use super::*;

pub(super) fn implied_kind(loader: &FileLoader, module_id: &str) -> Result<ModuleKind, String> {
    if module_id.ends_with(".mts") {
        return Ok(ModuleKind::Esm);
    }
    if module_id.ends_with(".cts") || module_id.starts_with("@remote/") {
        return Ok(ModuleKind::CommonJs);
    }
    let path = loader.source_path(module_id)?;
    let directory = path
        .parent()
        .ok_or_else(|| "Node source has no parent".to_string())?;
    let resolver = loader.packages.as_ref().unwrap_or(&loader.relative);
    resolver
        .is_es_module_scope(directory)
        .map(|esm| {
            if esm {
                ModuleKind::Esm
            } else {
                ModuleKind::CommonJs
            }
        })
        .map_err(|error| error.to_string())
}

pub(super) fn declaration_extension(javascript_extension: &str) -> &'static str {
    match javascript_extension {
        "mjs" => "d.mts",
        "cjs" => "d.cts",
        _ => "d.ts",
    }
}
